/*
  用户协议与隐私说明。
  条文沿用 Web 版 legal 页，针对小程序做了两处事实性调整（不能照抄 Web 版说法）：
    1. 存储位置：Web 版说「保存在当前浏览器本地存储」，小程序应说「保存在小程序本地存储」；
    2. 天气数据：Web 版说「浏览器不直接访问第三方」，小程序应说「小程序不直接访问第三方」。
  正文用 runs 表示（b=true 为强调），渲染时逐个 text 拼在一行，避免在小程序里引入富文本组件。
*/

/* 给每一段、每一项、每一段文字编号，供 wx:key 使用，避免运行时告警 */
function mk() {
  return Array.prototype.join.call(arguments, "-");
}

/* 把 runs（字符串或 {t, b}）补齐 b 与 k，渲染时 WXML 里不必再做判断 */
function runs(list, scope) {
  return list.map((run, i) => ({
    ...(typeof run === "string" ? { t: run, b: false } : run),
    k: mk(scope, "r", i)
  }));
}

function build(scope, sections) {
  return sections.map((sec, si) => ({
    title: sec.title,
    blocks: sec.blocks.map((blk, bi) => {
      const at = mk(scope, si, bi);
      if (blk.type === "list") {
        return {
          type: "list",
          items: blk.items.map((item, ii) => ({ k: mk(at, "i", ii), runs: runs(item, mk(at, "i", ii)) }))
        };
      }
      return { type: "p", k: at, runs: runs(blk.runs, at) };
    })
  }));
}

